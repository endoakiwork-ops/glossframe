import { mkdir, access, writeFile, rename, readdir, copyFile, stat } from 'node:fs/promises';
import { V5_EN_MOBILE_INT8_MODEL } from 'ppu-paddle-ocr/web';
const target = new URL('../public/models/ocr/v5-en-int8/', import.meta.url);
await mkdir(target, {recursive:true});
for (const [name,url] of [['det.ort',V5_EN_MOBILE_INT8_MODEL.detection],['rec.ort',V5_EN_MOBILE_INT8_MODEL.recognition],['dict.txt',V5_EN_MOBILE_INT8_MODEL.charactersDictionary]]) {
  const dest = new URL(name,target);
  try { await access(dest); continue; } catch {}
  console.log(`Downloading OCR ${name}`);
  const response = await fetch(url);
  if (!response.ok) throw new Error(`OCR download failed: ${response.status} ${url}`);
  const bytes = new Uint8Array(await response.arrayBuffer());
  if (!bytes.length || bytes.length > 25*1024*1024) throw new Error(`Invalid asset size: ${name}`);
  const tmp = new URL(name+'.tmp',target);
  await writeFile(tmp,bytes); await rename(tmp,dest);
}
const runtime = new URL('../node_modules/onnxruntime-web/dist/',import.meta.url);
for (const name of await readdir(runtime)) {
  if (/^ort-wasm-simd-threaded\.(mjs|wasm)$/.test(name)) await copyFile(new URL(name,runtime), new URL(name,target));
}

const requiredFiles = ['det.ort', 'rec.ort', 'dict.txt', 'ort-wasm-simd-threaded.mjs', 'ort-wasm-simd-threaded.wasm'];
const files = [];
let totalBytes = 0;
for (const name of requiredFiles) {
  const fileStat = await stat(new URL(name, target));
  files.push({ name, size: fileStat.size });
  totalBytes += fileStat.size;
}

const manifest = {
  version: 'v1',
  cacheName: 'paddle-v5-en-int8-v1',
  basePath: '/models/ocr/v5-en-int8/',
  totalBytes,
  files,
};

await writeFile(new URL('manifest.json', target), JSON.stringify(manifest, null, 2) + '\n');

const sharedTsPath = new URL('../src/shared/ocr-manifest.ts', import.meta.url);
const sharedTsContent = `// Generated by scripts/prepare-paddle-models.mjs. Do not edit directly.
export interface OcrModelFile {
  name: string;
  size: number;
}

export interface OcrManifest {
  version: string;
  cacheName: string;
  basePath: string;
  totalBytes: number;
  files: OcrModelFile[];
}

export const PADDLE_OCR_MANIFEST: OcrManifest = ${JSON.stringify(manifest, null, 2)} as const;
`;
await writeFile(sharedTsPath, sharedTsContent);

console.log('PaddleOCR model and WASM assets ready (manifest updated, total: ' + totalBytes + ' bytes)');
